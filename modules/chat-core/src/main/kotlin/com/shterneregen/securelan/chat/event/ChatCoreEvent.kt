package com.shterneregen.securelan.chat.event

/**
 * Sealed marker interface for all events emitted by the chat-core module.
 *
 * Concrete implementations are dispatched via [com.shterneregen.securelan.chat.service.ChatEventPublisher]
 * and cover the full lifecycle of a chat session: connection, messaging, signalling, and errors.
 *
 * Use an exhaustive `when` expression on this type to handle every possible event category:
 * ```kotlin
 * when (event) {
 *     is ChatConnectedEvent       -> ...
 *     is ChatDisconnectedEvent    -> ...
 *     is ChatMessageReceivedEvent -> ...
 *     is ChatMessageSentEvent     -> ...
 *     is ChatUserJoinedEvent      -> ...
 *     is ChatUserLeftEvent        -> ...
 *     is ChatSignalReceivedEvent  -> ...
 *     is ChatErrorEvent           -> ...
 * }
 * ```
 */
sealed interface ChatCoreEvent
